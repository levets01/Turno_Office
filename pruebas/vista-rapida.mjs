import { chromium } from '@playwright/test'
console.log('launch')
const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome-stable',headless:true,timeout:15000,args:['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
console.log('launched')
const page = await browser.newPage({viewport:{width:1440,height:1000}})
page.setDefaultTimeout(15000)
page.on('pageerror',e=>console.log('PAGE ERROR', e.message))
page.on('console',e=>{if(e.type()==='error')console.log('CONSOLE ERROR',e.text())})
console.log('goto')
await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded',timeout:20000})
console.log('loaded')
await page.waitForTimeout(4000)
console.log('body', (await page.locator('body').innerText()).slice(0,1000))
console.log('canvases',await page.locator('canvas').count())
await page.screenshot({path:'pruebas/capturas/vista-rapida.png',timeout:15000})
console.log('screenshot')
await browser.close()
